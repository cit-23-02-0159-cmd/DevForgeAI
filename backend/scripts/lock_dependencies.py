"""Snapshot installed dependency closures for reproducible development and containers.

Run with the backend virtual environment after installing .[dev].
"""

from importlib.metadata import distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def snapshot(include_dev: bool) -> str:
    project = distribution("devforge-api")
    queue = [
        Requirement(raw)
        for raw in project.requires or []
        if Requirement(raw).marker is None
        or Requirement(raw).marker.evaluate({"extra": "dev" if include_dev else ""})
    ]
    versions: dict[str, str] = {}
    visited: set[tuple[str, tuple[str, ...]]] = set()
    while queue:
        requirement = queue.pop()
        name = canonicalize_name(requirement.name)
        key = (name, tuple(sorted(requirement.extras)))
        if key in visited:
            continue
        visited.add(key)
        package = distribution(name)
        versions[name] = package.version
        for raw in package.requires or []:
            dependency = Requirement(raw)
            if dependency.marker is None or any(
                dependency.marker.evaluate({"extra": extra})
                for extra in {"", *requirement.extras}
            ):
                queue.append(dependency)
    return "# Generated by scripts/lock_dependencies.py on Python 3.12.\n" + "".join(
        f"{name}=={version}\n" for name, version in sorted(versions.items())
    )


if __name__ == "__main__":
    (ROOT / "requirements.lock").write_text(snapshot(False), encoding="utf-8")
    (ROOT / "requirements-dev.lock").write_text(snapshot(True), encoding="utf-8")
